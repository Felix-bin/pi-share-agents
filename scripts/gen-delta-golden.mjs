#!/usr/bin/env node
/**
 * Golden-fixture generator for the delta codec (task card P4-1).
 *
 * The Python reference implementation in the SYNAPSE repository is the prior
 * art for this wire format, so the TypeScript port is pinned to it byte for
 * byte: this script runs that reference over a few fixed inputs and writes
 * every observable output of one encode/decode cycle into
 * test/fixtures/delta-golden.json. The unit test then replays the same inputs
 * through src/synapse/delta.ts and compares the bytes; the fixture is committed
 * so the test suite never needs Python.
 *
 * Two properties of the reference shape the fixture and are worth stating once:
 *
 *  - Its quantizer rounds half to even (Python's round), while JavaScript's
 *    Math.round rounds half up. Case g3 is built out of eighth-grid values so
 *    v * grid lands exactly on .5 for about half its components, which makes the
 *    two roundings disagree loudly instead of silently.
 *  - It works on float64 lists, while the port takes Float32Array. Every value
 *    written here is therefore cast through float32 first, so both languages
 *    quantize the identical double rather than two neighbours of it.
 *
 * Usage:
 *   node scripts/gen-delta-golden.mjs --synapse-root <dir> [--out <file>] [--python <exe>]
 *
 * --synapse-root must be the checkout that holds src/synapse/stateplane/residual.py
 * (defaults to $SYNAPSE_SRC_ROOT). --python defaults to that checkout's own
 * virtualenv, then to $SYNAPSE_PYTHON.
 */
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const FIXTURE_HEADER =
	"Generated by scripts/gen-delta-golden.mjs from the Python reference implementation; do not edit by hand. " +
	"The unit test replays these inputs through src/synapse/delta.ts and compares payload bytes and decoded values.";

const FIXTURE_PARAMETERS_NOTE =
	"grid and threshold here are construction inputs for the codec, not measured settings: P4-1 lands before P4-2 calibrates the frozen pair. " +
	"g3 uses threshold 1.0 for exactly one reason — it cannot be reached before the last non-zero component, which is what makes its zero tail reachable.";

const FIXTURE_COVERAGE_NOTE =
	"coverage describes how each pair was constructed, not what the codec produced: exactHalfTies counts components landing on an exact .5 before rounding, " +
	"clampedComponents counts corrections outside the signed-byte range, nonzeroComponents counts non-zero quantized target components. " +
	"The unit test recomputes all three rather than trusting them.";

/**
 * The cases. `mode` selects how the reference generates the pair; the numbers
 * are seeds and mix factors, not expected outputs, so the fixture stays
 * reproducible from this file alone.
 */
function caseSpecs() {
	return [
		{
			// Realistic float32 values: most components quantize off the .5 grid, the
			// base sits at cosine ~0.89, so the encoder stops on the threshold with a
			// non-empty payload.
			name: "g1-similar-base",
			mode: "lcg-float32",
			dim: 320,
			grid: 64,
			threshold: 0.97,
			seed: 20260919,
			mix: 0.5,
			baseMemoryId: "mem-golden-g1",
		},
		{
			// The receiver's prediction already equals the target: nothing to send.
			// Deliberately small — an empty payload has no index column, so this case
			// says nothing about index width either way.
			name: "g2-perfect-base",
			mode: "perfect",
			dim: 64,
			grid: 64,
			threshold: 0.97,
			seed: 777,
			baseMemoryId: "mem-golden-g2",
		},
		{
			// Eighth-grid values give exact .5 ties for round-half-even; the
			// anti-correlated base drives residuals past the int8 range, and the
			// periodic zero components sit at the tail of the magnitude order, where
			// the "residual is zero, stop" branch is the only thing that can end the
			// loop.
			name: "g3-ties-clamp-and-zero-tail",
			mode: "dyadic-anti",
			dim: 1024,
			grid: 64,
			threshold: 1.0,
			seed: 31337,
			zeroEvery: 64,
			baseMemoryId: "mem-golden-g3",
		},
	];
}

/** The reference program, fed to the interpreter on stdin so nothing is quoted twice. */
function referenceProgram() {
	return String.raw`
import hashlib
import json
import math
import os
import struct
import sys

SRC_ROOT = sys.argv[1]
# The checkout keeps the package under src/; putting that on the path is what
# makes the import below load the reference the digest describes, rather than
# whichever copy the interpreter's environment happens to hold.
sys.path.insert(0, os.path.join(SRC_ROOT, "src"))

from synapse.stateplane import residual as residual_module

SPEC = json.loads(sys.argv[2])


def lcg(seed, n):
    x = seed
    out = []
    for _ in range(n):
        x = (1103515245 * x + 12345) % 2147483648
        out.append((x / 2147483648.0) * 2.0 - 1.0)
    return out


def lcg_raw(seed, n):
    x = seed
    out = []
    for _ in range(n):
        x = (1103515245 * x + 12345) % 2147483648
        out.append(x)
    return out


def f32(value):
    # The port consumes Float32Array; casting here keeps both languages on the
    # same double instead of comparing two neighbouring ones.
    return struct.unpack("<f", struct.pack("<f", value))[0]


class Cfg:
    def __init__(self, grid, threshold):
        self.quant_grid = grid
        self.verify_threshold = threshold


def build(case):
    dim = case["dim"]
    if case["mode"] == "lcg-float32":
        y = [f32(v) for v in lcg(case["seed"], dim)]
        mix = case["mix"]
        b = [f32(mix * value + (1.0 - mix) * f32(((i * 37) % 101) / 101.0 - 0.5)) for i, value in enumerate(y)]
        return y, b
    if case["mode"] == "perfect":
        y = [f32(v) for v in lcg(case["seed"], dim)]
        return y, list(y)
    if case["mode"] == "dyadic-anti":
        ks = [0 if i % case["zeroEvery"] == 0 else (r % 257) - 128 for i, r in enumerate(lcg_raw(case["seed"], dim))]
        y = [f32(k / 128.0) for k in ks]
        return y, [-value for value in y]
    raise SystemExit("unknown mode: " + case["mode"])


def coverage(y, b, grid):
    """Facts about this pair that the fixture should be able to prove downstream."""
    ties = 0
    clamped = 0
    nonzero = 0
    for index, value in enumerate(y):
        scaled = value * grid
        if scaled - math.floor(scaled) == 0.5:
            ties += 1
        residual = int(round(value * grid)) - int(round(b[index] * grid))
        if max(-127, min(127, residual)) != residual:
            clamped += 1
        if int(round(value * grid)) != 0:
            nonzero += 1
    return {"exactHalfTies": ties, "clampedComponents": clamped, "nonzeroComponents": nonzero}


cases = []
for case in SPEC["cases"]:
    y, b = build(case)
    codec = residual_module.ResidualCodec(Cfg(case["grid"], case["threshold"]))
    packet = codec.encode(y, b, case["baseMemoryId"])
    bq = [int(round(value * case["grid"])) for value in b]
    yhat = codec.decode_bytes(packet.residual, bq, case["dim"])
    cases.append(
        {
            "name": case["name"],
            "dim": case["dim"],
            "grid": case["grid"],
            "threshold": case["threshold"],
            "baseMemoryId": case["baseMemoryId"],
            "y": y,
            "b": b,
            "nnz": packet.nnz,
            "payloadHex": packet.residual.hex(),
            "yhat": yhat,
            "coverage": coverage(y, b, case["grid"]),
        }
    )

# The digest describes the file that actually produced the bytes above, so a
# run that silently imported a different copy cannot claim this one's identity.
with open(residual_module.__file__, "rb") as handle:
    reference_digest = hashlib.sha256(handle.read()).hexdigest()

sys.stderr.write("imported reference from: " + os.path.abspath(residual_module.__file__) + "\n")
sys.stdout.write(
    json.dumps(
        {
            "reference": {
                "module": "src/synapse/stateplane/residual.py",
                "sha256": reference_digest,
                "indexBytes": 2,
                "stride": 3,
                "note": (
                    "The reference selects its index width from the dimension (one byte up to 256, two above) while the port fixes two bytes "
                    "at every dimension, so the two layouts are comparable only above 256 dimensions. Every case with a non-empty payload "
                    "here is above 256; g2 is below it but emits nothing, so this fixture does not pin index width in that regime."
                ),
            },
            "cases": cases,
        }
    )
)
`;
}

function usageAndExit(message) {
	console.error(message);
	console.error("usage: node scripts/gen-delta-golden.mjs --synapse-root <dir> [--out <file>] [--python <exe>]");
	console.error("       --synapse-root defaults to $SYNAPSE_SRC_ROOT; --python defaults to that checkout's virtualenv.");
	process.exit(2);
}

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const args = process.argv.slice(2);
const flagsWithValue = new Set(["--synapse-root", "--out", "--python"]);
const values = new Map();
for (let index = 0; index < args.length; index += 1) {
	const token = args[index];
	if (token === undefined || !token.startsWith("--")) usageAndExit(`unexpected argument: ${token}`);
	if (!flagsWithValue.has(token)) usageAndExit(`unknown flag: ${token}`);
	const value = args[index + 1];
	if (value === undefined || value.startsWith("--")) usageAndExit(`${token} requires a value`);
	values.set(token, value);
	index += 1;
}

const synapseRoot = values.get("--synapse-root") ?? process.env.SYNAPSE_SRC_ROOT;
if (synapseRoot === undefined || synapseRoot.length === 0) {
	usageAndExit("--synapse-root is required (or set SYNAPSE_SRC_ROOT)");
}
const residualPy = path.join(synapseRoot, "src", "synapse", "stateplane", "residual.py");
if (!fs.existsSync(residualPy)) {
	usageAndExit(`no Python reference at ${residualPy}`);
}
const defaultPython = path.join(synapseRoot, ".venv", process.platform === "win32" ? "Scripts" : "bin", process.platform === "win32" ? "python.exe" : "python");
const python = values.get("--python") ?? process.env.SYNAPSE_PYTHON ?? defaultPython;
// Only a value that names a location can be checked here; a bare command name is
// resolved by the spawn below, whose failure message is the accurate one.
if ((python.includes("/") || python.includes("\\")) && !fs.existsSync(python)) {
	usageAndExit(`no Python interpreter at ${python}; pass --python or set SYNAPSE_PYTHON`);
}

const outPath = path.resolve(projectRoot, values.get("--out") ?? path.join("test", "fixtures", "delta-golden.json"));
const specs = { cases: caseSpecs() };

const run = spawnSync(python, ["-", synapseRoot, JSON.stringify(specs)], {
	input: referenceProgram(),
	encoding: "utf-8",
	maxBuffer: 64 * 1024 * 1024,
});
if (run.error) {
	console.error(`failed to start ${python}: ${run.error.message}`);
	process.exit(1);
}
if (run.status !== 0) {
	console.error(`Python reference exited with status ${run.status}`);
	console.error(String(run.stderr ?? "").trim());
	process.exit(1);
}

let reference;
try {
	reference = JSON.parse(run.stdout);
} catch (error) {
	const message = error instanceof Error ? error.message : String(error);
	console.error(`Python reference did not emit usable JSON: ${message}`);
	process.exit(1);
}

const fixture = {
	"//": FIXTURE_HEADER,
	"//parameters": FIXTURE_PARAMETERS_NOTE,
	"//coverage": FIXTURE_COVERAGE_NOTE,
	generator: "scripts/gen-delta-golden.mjs",
	reference: reference.reference,
	cases: reference.cases,
};

// The shape below is what the unit test reads; a fixture that drifts silently
// would turn the golden comparison into a weaker test than it looks.
for (const one of fixture.cases) {
	if (one.nnz * 3 !== one.payloadHex.length / 2) {
		console.error(`case ${one.name}: payload length does not match nnz × stride`);
		process.exit(1);
	}
	if (one.yhat.length !== one.dim || one.y.length !== one.dim || one.b.length !== one.dim) {
		console.error(`case ${one.name}: vector length does not match dim`);
		process.exit(1);
	}
	// Below 257 dimensions the reference emits one-byte indices, so a non-empty
	// payload there would be validated against a stride it does not use. Refuse
	// the case instead of freezing numbers that mean something else.
	if (one.dim <= 256 && one.nnz > 0) {
		console.error(
			`case ${one.name}: dim ${one.dim} is in the reference's one-byte index regime, so a non-empty payload cannot be validated against stride 3. ` +
				"Keep sub-257 cases empty, or extend the generator and the unit test to both layouts first.",
		);
		process.exit(1);
	}
}

try {
	fs.mkdirSync(path.dirname(outPath), { recursive: true });
	fs.writeFileSync(outPath, `${JSON.stringify(fixture, null, 2)}\n`, "utf-8");
} catch (error) {
	const message = error instanceof Error ? error.message : String(error);
	console.error(`could not write the fixture to ${outPath}: ${message}`);
	process.exit(1);
}

const digest = createHash("sha256").update(fs.readFileSync(outPath)).digest("hex");
console.log(`wrote ${outPath}`);
console.log(`fixture sha256 ${digest}`);
console.log(`reference residual.py sha256 ${fixture.reference.sha256}`);
console.log(String(run.stderr ?? "").trim());
for (const one of fixture.cases) {
	console.log(
		`  ${one.name}: dim=${one.dim} grid=${one.grid} threshold=${one.threshold} nnz=${one.nnz} payload=${one.payloadHex.length / 2}B ` +
			`ties=${one.coverage.exactHalfTies} clamped=${one.coverage.clampedComponents} nonzero=${one.coverage.nonzeroComponents}`,
	);
}
